"""Generate ESP32 POSIX timezone rules from a pinned official Python tzdata snapshot.

Uses only the standard library. The resulting header is committed; firmware builds
do not download timezone data or need this script.
"""
from io import BytesIO
from pathlib import Path
import json
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parents[1]
REVISION = '0d4342c29e1f64211181cf8ad2276cfa59c094ce'  # python/tzdata 2026.6
URL = f'https://codeload.github.com/python/tzdata/zip/{REVISION}'


def main():
    with urllib.request.urlopen(URL, timeout=90) as response:
        archive = zipfile.ZipFile(BytesIO(response.read()))
    zones = {}
    for name in archive.namelist():
        if '/src/tzdata/zoneinfo/' not in name or name.endswith('/'):
            continue
        data = archive.read(name)
        if not data.startswith(b'TZif'):
            continue
        rule = data.rsplit(b'\n', 2)[-2].decode('ascii')
        if rule:
            zones[name.split('/src/tzdata/zoneinfo/', 1)[1]] = rule
    if len(zones) < 400:
        raise RuntimeError(f'Incomplete timezone snapshot: {len(zones)} zones')
    lines = ['#pragma once', '// Generated by tools/generate_timezone_rules.py; do not edit.',
             '// Source: official Python tzdata 2026.6 (IANA data, public domain).',
             f'// https://github.com/python/tzdata/tree/{REVISION}',
             '// Recurring POSIX rules; historical TZif transitions are not included.',
             'namespace timezone_rules {', 'struct Entry { const char *name; const char *rule; };',
             'static constexpr Entry Entries[] = {']
    for zone, rule in sorted(zones.items()):
        lines.append('    {' + json.dumps(zone) + ', ' + json.dumps(rule) + '},')
    lines += ['};', '} // namespace timezone_rules', '']
    target = ROOT / 'src/timezone_rules_data.h'
    target.write_text('\n'.join(lines), encoding='utf-8')
    print(f'Generated {len(zones)} timezone rules: {target}')


if __name__ == '__main__':
    main()
